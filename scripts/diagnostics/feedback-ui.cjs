const { app, BrowserWindow, session } = require('electron')
const { mkdtempSync, mkdirSync, writeFileSync, rmSync } = require('node:fs')
const { resolve, join } = require('node:path')
const { tmpdir } = require('node:os')
const assert = require('node:assert/strict')
const root = resolve(__dirname, '../..'), output = join(root, 'docs/ui-evidence/feedback-minimal')
const profile = mkdtempSync(join(tmpdir(), 'offkey-feedback-'))
app.setPath('userData', profile)
app.commandLine.appendSwitch('disable-background-networking')
let win
const failures = [], warnings = [], screenshots = []
async function js(expression) {
  try { return await win.webContents.executeJavaScript(expression) }
  catch (error) { throw Error(`${error.message}\nExpression: ${expression.slice(0, 240)}\n${failures.join('\n')}`) }
}
async function waitFor(expression) {
  for (let i = 0; i < 160; i++) {
    if (await js(expression)) return
    await new Promise(resolve => setTimeout(resolve, 40))
  }
  throw Error('UI timeout: ' + expression)
}
async function page(route, query = {}, file = 'hub.html') {
  await win.loadFile(join(root, '.build/ui-review', file), { hash: '/' + route, query })
  await waitFor("!!document.querySelector('#root')?.children.length")
  await js('document.fonts.ready')
}
async function click(selector) {
  await waitFor(`!!document.querySelector(${JSON.stringify(selector)}) && !document.querySelector(${JSON.stringify(selector)}).disabled`)
  await js(`(() => { const node = document.querySelector(${JSON.stringify(selector)}); node.scrollIntoView({block:'center'}); node.focus(); node.click() })()`)
  await js('new Promise(requestAnimationFrame)')
}
async function textClick(selector, text) {
  await waitFor(`[...document.querySelectorAll(${JSON.stringify(selector)})].some(node => node.textContent.trim() === ${JSON.stringify(text)} && !node.disabled)`)
  await js(`(() => { const node = [...document.querySelectorAll(${JSON.stringify(selector)})].find(node => node.textContent.trim() === ${JSON.stringify(text)}); node.focus(); node.click() })()`)
  await js('new Promise(requestAnimationFrame)')
}
async function input(selector, value) {
  await js(`(() => { const node = document.querySelector(${JSON.stringify(selector)}); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(node,${JSON.stringify(value)}); node.dispatchEvent(new Event('input',{bubbles:true})) })()`)
}
async function key(value, shiftKey = false) {
  await js(`document.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:${JSON.stringify(value)},shiftKey:${shiftKey},bubbles:true,cancelable:true}))`)
}
async function clearToasts() {
  await js("document.querySelectorAll('.offkey-toast').forEach(node => node.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true,cancelable:true})))")
  await waitFor("!document.querySelector('.offkey-toast')")
}
async function shot(name) {
  await js("new Promise(resolve => setTimeout(resolve,250))")
  assert.equal(await js('document.documentElement.scrollWidth > innerWidth'), false, name + ' overflow')
  writeFileSync(join(output, name + '.png'), (await win.webContents.capturePage()).toPNG())
  screenshots.push(name)
}
async function monochromeToast(tone) {
  await waitFor(`!!document.querySelector('.offkey-toast.is-${tone}')`)
  const style = await js(`(() => { const node = document.querySelector('.offkey-toast.is-${tone}'), style = getComputedStyle(node); return {background:style.backgroundColor,color:style.color,radius:style.borderRadius,buttons:node.querySelectorAll('button').length,mark:!!node.querySelector('.feedback-mark'),description:!!node.querySelector('.toast-description')} })()`)
  assert.equal(style.background, 'rgb(29, 26, 26)')
  assert.equal(style.color, 'rgb(255, 255, 255)')
  assert.equal(style.buttons, 0)
  assert.equal(style.mark, false)
  assert.equal(style.description, false)
}
async function layout(selector) {
  return js(`(() => { const node = document.querySelector(${JSON.stringify(selector)}); return {height:node.offsetHeight,scrollHeight:node.scrollHeight,children:node.querySelectorAll('*').length} })()`)
}
async function noInlineNotice(selector) {
  assert.equal(await js(`!!document.querySelector(${JSON.stringify(selector)}).querySelector('[role=alert],.provider-editor-status,.provider-model-feedback,.confirmation-error,.inline-error,.settings-error,.secondary-error')`), false, 'operation reports only through Toast')
}
async function confirmLayout() {
  await waitFor("!!document.querySelector('[role=alertdialog]')")
  assert.deepEqual(await js("[...document.querySelectorAll('[role=alertdialog] button')].map(node => node.textContent.trim())"), ['取消', '确认'])
  assert.equal(await js("!!document.querySelector('.confirmation-illustration,.confirmation-spark,.confirmation-dialog .modal-close')"), false)
  assert.equal(await js("document.activeElement.className"), 'confirmation-cancel')
  assert.equal(await js("getComputedStyle(document.querySelector('.confirmation-submit')).backgroundColor"), 'rgb(29, 26, 26)')
}
