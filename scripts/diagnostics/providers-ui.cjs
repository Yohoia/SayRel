async function focusClipping(selector) {
  if (!win.webContents.debugger.isAttached()) {
    win.webContents.debugger.attach('1.3')
    await win.webContents.debugger.sendCommand('DOM.enable')
    await win.webContents.debugger.sendCommand('CSS.enable')
  }
  await js(`document.querySelector(${JSON.stringify(selector)}).focus()`)
  const { root } = await win.webContents.debugger.sendCommand('DOM.getDocument')
  const { nodeId } = await win.webContents.debugger.sendCommand('DOM.querySelector', { nodeId: root.nodeId, selector })
  await win.webContents.debugger.sendCommand('CSS.forcePseudoState', { nodeId, forcedPseudoClasses: ['focus-visible'] })
  return js(`(() => {
    const node = document.querySelector(${JSON.stringify(selector)});
    const rect = node.getBoundingClientRect(), style = getComputedStyle(node);
    const halo = Math.max(0, parseFloat(style.outlineWidth) + parseFloat(style.outlineOffset));
    const clipped = [];
    for (let ancestor = node.parentElement; ancestor; ancestor = ancestor.parentElement) {
      const ancestorStyle = getComputedStyle(ancestor);
      if (/(auto|scroll|hidden|clip)/.test(ancestorStyle.overflowX)) {
        const bounds = ancestor.getBoundingClientRect(), left = bounds.left + ancestor.clientLeft;
        if (rect.left - halo < left - 0.5 || rect.right + halo > left + ancestor.clientWidth + 0.5) clipped.push(ancestor.className || ancestor.tagName);
      }
      if (ancestorStyle.position === 'fixed') break;
    }
    return clipped;
  })()`)
}
