const { app, BrowserWindow, ipcMain } = require('electron')
const { mkdtempSync, rmSync, writeFileSync, readFileSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join, resolve } = require('node:path')
const assert = require('node:assert/strict')
const profile = mkdtempSync(join(tmpdir(), 'offkey-provider-ipc-'))
app.setPath('userData', profile); app.setPath('logs', profile)
app.commandLine.appendSwitch('disable-background-networking')
let win
app.whenReady().then(async () => {
  const { registerProviderHandlers } = await import(resolve(__dirname, '../../.build/provider-settings/ipc.mjs'))
  registerProviderHandlers((channel, handler) => ipcMain.handle(channel, handler))
  const preload = join(profile, 'probe.cjs')
  writeFileSync(preload, "const {contextBridge,ipcRenderer}=require('electron');contextBridge.exposeInMainWorld('probe',{invoke:(...a)=>ipcRenderer.invoke(...a),on:(c,fn)=>{ipcRenderer.on(c,(_e,...a)=>fn(...a))}});")
  win = new BrowserWindow({ show: false, webPreferences: { preload, contextIsolation: true, sandbox: true } })
  await win.loadURL('data:text/html,<html><body>Provider IPC probe</body></html>')
  const invoke = (channel, action) => win.webContents.executeJavaScript(`window.probe.invoke(${JSON.stringify(channel)}${action ? ',' + JSON.stringify(action) : ''})`)
  assert.deepEqual((await invoke('providers:get')).profiles, [])
  await win.webContents.executeJavaScript("window.broadcasts=0;window.probe.on('store:changed',()=>window.broadcasts++)")
  const secret = 'ipc-secret-that-must-not-be-plaintext'
  const profileData = { id: 'ipc-profile', presetId: 'custom', name: 'Test provider', service: 'refinement', protocol: 'openai-chat', enabled: true, endpoint: 'http://127.0.0.1:3456/v1', apiKey: secret, models: ['fake-model'], appId: '', accessToken: '', resourceId: '', apiVersion: '' }
  const saved = await invoke('providers:manage', { action: 'save', profile: profileData, activateModel: 'fake-model' })
  assert.equal(saved.refinement.providerId, 'ipc-profile')
  assert.equal((await invoke('providers:get')).profiles[0].apiKey, secret)
  assert.equal(readFileSync(join(profile, 'settings.json'), 'utf8').includes(secret), false)
  assert.equal(await win.webContents.executeJavaScript('window.broadcasts'), 1)
  await assert.rejects(() => invoke('providers:manage', { action: 'select', service: 'transcription', selection: { providerId: 'ipc-profile', model: 'fake-model' } }))
  await assert.rejects(() => invoke('providers:manage', { action: 'save', profile: { ...profileData, endpoint: 'file:///tmp/secret' } }))
  await assert.rejects(() => invoke('providers:manage', { action: 'save', profile: { ...profileData, protocol: 'qwen-asr' } }))
  await assert.rejects(() => invoke('providers:manage', { action: 'save', profile: { ...profileData, models: [] } }))
  const removed = await invoke('providers:manage', { action: 'remove', id: profileData.id })
  assert.deepEqual(removed, { profiles: [], transcription: null, refinement: null })
  assert.equal(JSON.parse(readFileSync(join(profile, 'settings.json'), 'utf8')).encryptedProviderSecrets, undefined)
  console.log('PASS real Electron IPC: save/read/broadcast, encrypted disk, role/protocol/URL/model validation, removal clears default and credentials')
}).catch(error => { console.error(error); process.exitCode = 1 }).finally(() => {
  win?.destroy(); rmSync(profile, { recursive: true, force: true }); app.exit(process.exitCode || 0)
})
