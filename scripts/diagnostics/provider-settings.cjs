// Run with Electron after bundling src/main/lib/settings.ts to .build/provider-settings/settings.mjs.
const { app, safeStorage } = require('electron')
const { mkdtempSync, rmSync, writeFileSync, readFileSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join, resolve } = require('node:path')
const assert = require('node:assert/strict')
const profile = mkdtempSync(join(tmpdir(), 'sayrel-provider-settings-'))
app.setPath('userData', profile)
app.commandLine.appendSwitch('disable-background-networking')
const apiKey = 'sayrel-settings-test-secret-unique'
const legacy = { transcription: 'openai-compatible', refinement: 'openai-compatible', baseUrl: 'https://example.test/v1', apiKey: null, model: 'old-asr', refinementModel: 'old-llm' }
app.whenReady().then(async () => {
  assert.equal(safeStorage.isEncryptionAvailable(), true, 'system encryption available in isolated test')
  const shortcut = { accelerator:'Control+K', enabled:true, style:'hold' }
  writeFileSync(join(profile, 'settings.json'), JSON.stringify({ settings: { language:'zh-CN', provider:legacy, shortcut, translationTargetLanguages:['zh-CN', 'ja'], translationTargetLanguage:'ja' }, deviceId:'fixture-device', encryptedApiKey:safeStorage.encryptString(apiKey).toString('base64') }))
  const { settings } = await import(resolve(__dirname, '../../.build/provider-settings/settings.mjs'))
  const loaded = settings.get()
  assert.equal(loaded.language, 'zh-CN', 'loading an existing profile preserves its chosen interface language')
  assert.deepEqual(loaded.shortcut, shortcut, 'loading settings preserves custom shortcuts')
  assert.deepEqual(loaded.translationTargetLanguages, ['zh-CN', 'ja'], 'loading settings preserves translation candidates')
  assert.equal(loaded.translationTargetLanguage, 'ja', 'loading settings preserves the selected translation target')
  assert.equal(JSON.parse(readFileSync(join(profile, 'settings.json'), 'utf8')).deviceId, 'fixture-device')
  assert.equal(loaded.serviceProviders.profiles.length, 2)
  assert.equal(loaded.serviceProviders.profiles[0].apiKey, apiKey, 'encrypted legacy credentials migrate before provider profiles')
  assert.equal(loaded.serviceProviders.refinement.model, 'old-llm')
  const updated = { ...loaded.serviceProviders, profiles: loaded.serviceProviders.profiles.map(p => ({ ...p, apiKey: apiKey + p.id })) }
  settings.patch({ serviceProviders: updated })
  assert.equal(settings.get().serviceProviders.profiles[0].apiKey, apiKey + updated.profiles[0].id, 'saved key immediately usable')
  const readDisk = () => readFileSync(join(profile, 'settings.json'), 'utf8')
  assert.equal(readDisk().includes(apiKey), false)
  settings.patch({ launchAtLogin: true })
  assert.equal(readDisk().includes(apiKey), false, 'unrelated settings writes never leak secrets')
  settings.invalidateCache()
  assert.equal(settings.get().serviceProviders.profiles[0].apiKey, apiKey + updated.profiles[0].id, 'reload decrypts independent credentials')
  assert.equal(settings.get().provider.apiKey, apiKey)
  settings.patch({ language: 'zh-CN' })
  settings.invalidateCache()
  assert.equal(settings.get().language, 'zh-CN', 'later language choices survive reloads and unrelated writes')
  settings.patch({ soundVolume: 0.5 })
  assert.equal(readDisk().includes(apiKey), false, 'read-decrypt-write remains encrypted')
  const disabled = { ...settings.get().serviceProviders, refinement: null, profiles: settings.get().serviceProviders.profiles.map(p => p.service === 'refinement' ? { ...p, enabled: false } : p) }
  settings.patch({ serviceProviders: disabled })
  settings.invalidateCache()
  assert.equal(settings.get().serviceProviders.refinement, null)
  assert.throws(() => settings.patch({ serviceProviders: { ...disabled, refinement: { providerId: 'missing', model: 'bad' } } }))
  settings.reset()
  settings.invalidateCache()
  assert.equal(settings.get().serviceProviders.profiles.length, 0)
  assert.equal(settings.get().provider.apiKey, null)
  const disk = JSON.parse(readDisk())
  assert.equal(disk.encryptedProviderSecrets, undefined)
  assert.equal(disk.encryptedApiKey, undefined)
  console.log('PASS provider settings: encrypted migration, immediate use, save/reload, unrelated writes, validation and reset')
}).catch(error => { console.error(error); process.exitCode = 1 }).finally(() => {
  rmSync(profile, { recursive: true, force: true }); app.exit(process.exitCode || 0)
})
